export function getDb() {
  const existing = readJson(STORAGE_KEYS.DB, null)
  if (existing?.users) return existing
  const created = seed()
  persist(created)
  return created
}

export function saveDb(db) {
  persist(db)
}

export function resetDb() {
  const created = seed()
  persist(created)
  return created
}

export function delay(ms = 280) {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

export function nextId(prefix) {
  return uid(prefix)
}
